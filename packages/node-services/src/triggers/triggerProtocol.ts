/*---------------------------------------------------------------------------------------------
 *  Copyright (c) Universe Editor Authors. All rights reserved.
 *  Wire contract of the remote `triggerPoll` channel (RemoteChannels.TriggerPoll).
 *
 *  Trigger definitions and the scheduler stay on the CLIENT (the editor's main
 *  process); only the three host-bound pieces cross the tunnel: running the
 *  user's poll command in a workspace, carving out / pruning a per-run directory
 *  that the remote agent session can write to, and reading back one run's
 *  report.md for the desktop report tab and the phone gateway.
 *
 *  Invariants:
 *   - Every path in the DTOs is a URI; the per-connection codec translates
 *     remote-ssh <-> file, so the server stays a headless local file-service.
 *   - The server owns the run-directory layout (`<dataDir>/triggers/runs/
 *     <clientId>/<runId>`); a client never sends a path, only ids. clientId is
 *     the client installation id, so two editors sharing one remote host prune
 *     only their own runs.
 *   - Payload values are the trigger's scalar payload vocabulary (string /
 *     number / boolean). The editor's shared trigger types mirror this shape.
 *--------------------------------------------------------------------------------------------*/

import type { URI } from '@universe-editor/platform'

/** Scalar payload a poll item may carry into the trigger prompt. */
export type TriggerPayloadValue = string | number | boolean

export interface TriggerPollItem {
  /** Raw value of `keyField`; the scheduler prefixes it with `poll:`. */
  readonly key: string
  readonly payload: Readonly<Record<string, TriggerPayloadValue>>
}

export type TriggerPollResult =
  | { readonly ok: true; readonly items: readonly TriggerPollItem[] }
  | { readonly ok: false; readonly error: string }

export interface TriggerPollRequest {
  readonly command: string
  /** Workspace folder the command runs in; wire DTO: a URI. */
  readonly cwd: URI
  readonly timeoutSec: number
  readonly keyField: string
}

/** How many run directories to keep, and which run ids must survive. */
export interface TriggerRunDirectoryOptions {
  /** Directories kept per client (newest by mtime); protected ids are extra. */
  readonly keep: number
  /** Run ids still active / queued / pending on the client. */
  readonly protectedRunIds: readonly string[]
}

export interface TriggerRunReportReadOptions {
  readonly maxBytes?: number
}

export type TriggerRunReportReadResult =
  | {
      readonly ok: true
      readonly bytes: Uint8Array
      /** Resolved run directory (base for relative resources in the report). */
      readonly runDir: URI
      /** Report file mtime; the closest thing to the run's completion time. */
      readonly modifiedAt: number
    }
  | { readonly ok: false; readonly reason: 'not_found' | 'too_large' }

export interface IRemoteTriggerService {
  /** Run the poll command on the server host and normalize its stdout. */
  poll(request: TriggerPollRequest): Promise<TriggerPollResult>

  /**
   * Create `<runsDir>/<clientId>/<runId>` and prune that client's older runs.
   * Throws for malformed ids; the client never supplies a path.
   */
  createRunDir(
    clientId: string,
    runId: string,
    options: TriggerRunDirectoryOptions,
  ): Promise<{ readonly runDir: URI }>

  /** Prune one client's runs; returns the run ids that were removed. */
  cleanupRuns(
    clientId: string,
    options: TriggerRunDirectoryOptions,
  ): Promise<{ readonly removed: readonly string[] }>

  /** Read `<runsDir>/<clientId>/<runId>/report.md` under a byte cap. */
  readReport(
    clientId: string,
    runId: string,
    options?: TriggerRunReportReadOptions,
  ): Promise<TriggerRunReportReadResult>
}

/** Installation ids are opaque tokens; keep them filesystem- and wire-safe. */
export const TRIGGER_CLIENT_ID_PATTERN = /^[A-Za-z0-9_-]{1,64}$/

export function isValidTriggerClientId(clientId: string): boolean {
  return TRIGGER_CLIENT_ID_PATTERN.test(clientId)
}

/** Run ids are UUIDs generated by the client scheduler. */
export const TRIGGER_RUN_ID_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i

export function isValidTriggerRunId(runId: string): boolean {
  return TRIGGER_RUN_ID_PATTERN.test(runId)
}
