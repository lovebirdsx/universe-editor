#!/usr/bin/env node
/*---------------------------------------------------------------------------------------------
 *  生成 SDK 版本常量文件：
 *    packages/create-extension/src/sdkVersions.ts
 *    packages/uex/src/lib/sdkVersion.ts
 *
 *  单一真相：packages/extension-api、packages/uex、packages/e2e-harness、
 *  packages/e2e-contract 的 package.json version，以及 pnpm-workspace.yaml catalog 里的
 *  esbuild / typescript / @types/node / vitest / @playwright/test。
 *
 *  幂等：内容没变化不写文件，避免无谓 mtime 变化触发 turbo 重建。
 *  路径解析基于本文件位置（import.meta.url），不依赖 CWD——两个包各自独立 build 都能生效。
 *
 *  用法: pnpm ext-packages:gen   （或 node scripts/ext-packages/generate-sdk-versions.mjs）
 *--------------------------------------------------------------------------------------------*/

import { readFileSync, writeFileSync, existsSync, realpathSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const defaultRepoRoot = resolve(__dirname, '..', '..')

function escapeRegExp(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

function readJson(repoRoot, relPath) {
  return JSON.parse(readFileSync(join(repoRoot, relPath), 'utf8'))
}

/** 从 pnpm-workspace.yaml 的 catalog 段读取指定 key 的版本区间。 */
function readCatalogVersion(repoRoot, key) {
  const text = readFileSync(join(repoRoot, 'pnpm-workspace.yaml'), 'utf8')
  const lines = text.split(/\r?\n/)
  let inCatalog = false
  for (const line of lines) {
    if (/^catalog:\s*$/.test(line)) {
      inCatalog = true
      continue
    }
    if (inCatalog) {
      if (/^\S/.test(line)) break
      const match = new RegExp(`^  (['"])?${escapeRegExp(key)}\\1:\\s*(.+)$`).exec(line)
      if (match) return match[2].trim()
    }
  }
  throw new Error(`无法从 pnpm-workspace.yaml catalog 解析 ${key}`)
}

const HEADER =
  '// Generated by scripts/ext-packages/generate-sdk-versions.mjs — do not edit by hand.\n' +
  '// Regenerate: pnpm ext-packages:gen\n'

function renderSdkVersionsTs({
  extensionApi,
  uex,
  esbuild,
  typescript,
  nodeTypes,
  vitest,
  playwright,
  e2eHarness,
  e2eContract,
}) {
  return (
    HEADER +
    '/**\n' +
    ' * Versions baked into generated projects. Derived at build time: extensionApi/uex/\n' +
    " * e2eHarness/e2eContract from the sibling packages' package.json,\n" +
    ' * esbuild/typescript/nodeTypes/vitest/@playwright/test from the pnpm-workspace.yaml\n' +
    ' * catalog. Guarded by a drift test.\n' +
    ' */\n' +
    'export interface SdkVersions {\n' +
    '  readonly extensionApi: string\n' +
    '  readonly uex: string\n' +
    '  readonly esbuild: string\n' +
    '  readonly typescript: string\n' +
    '  readonly nodeTypes: string\n' +
    '  readonly vitest: string\n' +
    '  readonly playwright: string\n' +
    '  readonly e2eHarness: string\n' +
    '  readonly e2eContract: string\n' +
    '}\n' +
    '\n' +
    'export const SDK_VERSIONS: SdkVersions = {\n' +
    `  extensionApi: '${extensionApi}',\n` +
    `  uex: '${uex}',\n` +
    `  esbuild: '${esbuild}',\n` +
    `  typescript: '${typescript}',\n` +
    `  nodeTypes: '${nodeTypes}',\n` +
    `  vitest: '${vitest}',\n` +
    `  playwright: '${playwright}',\n` +
    `  e2eHarness: '${e2eHarness}',\n` +
    `  e2eContract: '${e2eContract}',\n` +
    '}\n'
  )
}

function renderSdkVersionTs({ extensionApi }) {
  return (
    HEADER +
    '/**\n' +
    ' * The extension API version uex itself was built against — used by the\n' +
    ' * engines.universe coverage warning (authors most often target the current\n' +
    ' * API). Derived at build time from packages/extension-api/package.json.\n' +
    ' */\n' +
    `export const CURRENT_API_VERSION = '${extensionApi}'\n`
  )
}

/**
 * 读取真相源、渲染两个常量文件，内容有变化才写盘（dryRun 只报告不写）。
 * 返回 { updated: [相对路径] }。
 */
export function generateSdkVersions({ repoRoot = defaultRepoRoot, dryRun = false } = {}) {
  const extensionApi = readJson(repoRoot, 'packages/extension-api/package.json').version
  const uex = readJson(repoRoot, 'packages/uex/package.json').version
  const e2eHarness = readJson(repoRoot, 'packages/e2e-harness/package.json').version
  const e2eContract = readJson(repoRoot, 'packages/e2e-contract/package.json').version
  const esbuild = readCatalogVersion(repoRoot, 'esbuild')
  const typescript = readCatalogVersion(repoRoot, 'typescript')
  const nodeTypes = readCatalogVersion(repoRoot, '@types/node')
  const vitest = readCatalogVersion(repoRoot, 'vitest')
  const playwright = readCatalogVersion(repoRoot, '@playwright/test')

  const targets = [
    {
      rel: 'packages/create-extension/src/sdkVersions.ts',
      content: renderSdkVersionsTs({
        extensionApi,
        uex,
        esbuild,
        typescript,
        nodeTypes,
        vitest,
        playwright,
        e2eHarness,
        e2eContract,
      }),
    },
    {
      rel: 'packages/uex/src/lib/sdkVersion.ts',
      content: renderSdkVersionTs({ extensionApi }),
    },
  ]

  const updated = []
  for (const { rel, content } of targets) {
    const abs = join(repoRoot, rel)
    const current = existsSync(abs) ? readFileSync(abs, 'utf8') : null
    if (current === content) continue
    if (!dryRun) writeFileSync(abs, content)
    updated.push(rel)
  }
  return { updated }
}

const isMain = process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const { updated } = generateSdkVersions()
  if (updated.length === 0) console.log('sdk versions: 已是最新，无文件更新')
  else for (const rel of updated) console.log(`sdk versions: 已更新 ${rel}`)
}
